#pragma once

#include <vector>
#include <string>
#include <string_view>
#include "../Tensor.hpp"
#include "../EngineContext.hpp"

/**
 * @brief Strongly typed enumeration tracking structural layer classifications.
 * Replaces expensive runtime RTTI operations with deterministic identifier markers.
 */
enum class LayerType : uint8_t {
    FullyConnected = 0,
    Conv2D,
    Activation_ReLU
};

/**
 * @brief Pure Abstract Base Interface for all Computational Network Nodes.
 * Enforces strict, zero-allocation forward contracts across all derivation structures.
 */
class ILayer {
public:
    ILayer() noexcept = default;
    virtual ~ILayer() = default;

    // Prohibit dynamic replication mechanics across active polymorphic layers
    ILayer(const ILayer&) = delete;
    ILayer& operator=(const ILayer&) = delete;
    ILayer(ILayer&&) noexcept = default;
    ILayer& operator=(ILayer&&) noexcept = default;

    /**
     * @brief High-speed computational pass transforming inputs into outputs.
     * @param context Global runtime engine safety manager.
     * @param input Direct immutable reference containing source activation vectors.
     * @param output Direct mutable target buffer capturing layer evaluations.
     * @return EngineStatus Evaluation metric verifying functional completeness.
     */
    virtual EngineStatus forward(
        EngineContext& context, 
        const Tensor& input, 
        Tensor& output
    ) noexcept = 0;

    /**
     * @brief Validates input and calculates the exact spatial dimensions generated by this layer.
     * @param input_shape Geometric layout profile arriving from the preceding graph layer.
     * @return std::vector<size_t> Calculated structural boundaries produced by this operational step.
     */
    [[nodiscard]] virtual std::vector<size_t> compute_output_shape(
        const std::vector<size_t>& input_shape
    ) const noexcept = 0;

    /**
     * @brief Reflection routine delivering the explicit layer classification.
     */
    [[nodiscard]] virtual LayerType get_type() const noexcept = 0;

    /**
     * @brief Human-readable string representation mapping node nomenclature for logging or GUI tracking.
     */
    [[nodiscard]] virtual std::string_view get_name() const noexcept = 0;
};