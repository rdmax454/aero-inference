#pragma once

#include "ILayer.hpp"
#include "../MathBackend.hpp"
#include <string_view>
#include <utility>

/**
 * @brief Industrial-Grade Fully Connected (Dense) Computational Layer.
 * Manages layer param tensor mapping and maps affine transformations smoothly via MathBackend.
 */
class DenseLayer final : public ILayer {
private:
    size_t m_input_dim{0};
    size_t m_output_dim{0};
    
    // Model parameters (Layer Weights and Biases)
    Tensor m_weights; // Structural shape expected: {input_dim, output_dim}
    Tensor m_bias;    // Structural shape expected: {output_dim}
    
    std::string m_name;

public:
    /**
     * @brief Constructor initializing structural dimensions and parameter references.
     * @param name Unique identifier nomenclature for GUI logging or graph mapping.
     * @param input_dim Total input neurons coming into this layer node.
     * @param output_dim Total output neurons generated by this layer node.
     * @param weights Parameter tensor containing pre-trained model connection weights.
     * @param bias Parameter tensor containing pre-trained layer offset weights.
     */
    DenseLayer(std::string name, size_t input_dim, size_t output_dim, Tensor&& weights, Tensor&& bias) noexcept
        : m_input_dim(input_dim), 
          m_output_dim(output_dim), 
          m_weights(std::move(weights)), 
          m_bias(std::move(bias)), 
          m_name(std::move(name)) {}

    ~DenseLayer() override = default;

    // Enforce strict asset ownership: ban duplication paths
    DenseLayer(const DenseLayer&) = delete;
    DenseLayer& operator=(const DenseLayer&) = delete;
    DenseLayer(DenseLayer&&) noexcept = default;
    DenseLayer& operator=(DenseLayer&&) noexcept = default;

    /**
     * @brief Computes high-performance forward inference via our optimized MathBackend.
     */
    EngineStatus forward(EngineContext& context, const Tensor& input, Tensor& output) noexcept override {
        // Runtime Sanity Assertions: Only checked in Debug configurations
#ifndef NDEBUG
        if (input.size() != m_input_dim) {
            context.log_error(StatusCode::Error_DimensionMismatch, 
                "DenseLayer [" + m_name + "] Runtime failure: Input tensor dimension size mismatch.");
            return EngineStatus{StatusCode::Error_DimensionMismatch, "Input dimension mismatch."};
        }
        if (output.size() != m_output_dim) {
            context.log_error(StatusCode::Error_DimensionMismatch, 
                "DenseLayer [" + m_name + "] Runtime failure: Target output tensor allocation layout mismatch.");
            return EngineStatus{StatusCode::Error_DimensionMismatch, "Output dimension mismatch."};
        }
#endif

        // Delegate linear algebra transformation to our hardware-optimized math kernel
        return MathBackend::fully_connected_forward(
            input.data(),
            m_weights.data(),
            m_bias.data(),
            output.data(),
            m_input_dim,
            m_output_dim
        );
    }

    /**
     * @brief Validates input mapping constraints and returns the calculated output topology shape.
     */
    [[nodiscard]] std::vector<size_t> compute_output_shape(const std::vector<size_t>& input_shape) const noexcept override {
        if (input_shape.empty()) return {};
        
        // Industrial engines assume inputs are flat or flattened vectors for dense layers:
        // Input shape typically resolves to a single-dimensional vector structure like {input_dim}
        size_t total_incoming_features = 1;
        for (size_t dim : input_shape) {
            total_incoming_features *= dim;
        }

        if (total_incoming_features != m_input_dim) {
            return {}; // Returning an empty shape signals a topological validation error to the network compiler
        }

        return { m_output_dim };
    }

    // System Utilities and Reflection Functions
    [[nodiscard]] LayerType get_type() const noexcept override { 
        return LayerType::FullyConnected; 
    }
    
    [[nodiscard]] std::string_view get_name() const noexcept override { 
        return m_name; 
    }

    [[nodiscard]] size_t input_dim() const noexcept { return m_input_dim; }
    [[nodiscard]] size_t output_dim() const noexcept { return m_output_dim; }
    [[nodiscard]] const Tensor& weights() const noexcept { return m_weights; }
    [[nodiscard]] const Tensor& bias() const noexcept { return m_bias; }
};