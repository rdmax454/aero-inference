#pragma once

#include <cstddef>
#include "EngineContext.hpp"

/**
 * @brief Unified Hardware Acceleration & Computational Kernel Gateway.
 * Isolates numerical linear algebra routines to allow modular optimization across target chips.
 */
class MathBackend {
public:
    // Enforce static utility structural rules; instantiation of this class is prohibited
    MathBackend() = delete;
    ~MathBackend() = delete;
    MathBackend(const MathBackend&) = delete;
    MathBackend& operator=(const MathBackend&) = delete;

    /**
     * @brief Computes high-performance Matrix Multiplication (Gemm) optimized for cache lines.
     * Math formula representation: Output = (Input * Weights) + Bias
     * * @param input Flat pointer to the incoming array. Shape: [1 x input_dim]
     * @param weights Flat pointer to the layer weight parameter matrix. Shape: [input_dim * output_dim]
     * @param bias Flat pointer to the layer bias parameter vector. Shape: [output_dim]
     * @param output Flat destination pointer for computed outcomes. Shape: [output_dim]
     * @param input_dim Structural column size of the input / row size of weights.
     * @param output_dim Structural column size of weights / output length.
     * @return EngineStatus Tracking structure indicating calculation execution metrics.
     */
    static EngineStatus fully_connected_forward(
        const float* __restrict input,
        const float* __restrict weights,
        const float* __restrict bias,
        float* __restrict output,
        size_t input_dim,
        size_t output_dim
    ) noexcept;

    /**
     * @brief High-performance Rectified Linear Unit (ReLU) element-wise activation layer.
     * Math formulation: f(x) = max(0, x)
     * * @param data Flat target array to be activated in-place.
     * @param size Total element boundaries of the target collection.
     */
    static void relu_activation(float* data, size_t size) noexcept;

    /**
     * @brief Performs spatial 2D Cross-Correlation/Convolution calculation passes.
     * * @param input Flat input image tensor pointer. Shape: [channels * height * width]
     * @param kernel Flat array containing trained weight filter coefficients.
     * @param output Destination array mapping visual features.
     * @param in_channels Channel counts of incoming data maps.
     * @param out_channels Feature depth volume size generated by convolution filters.
     * @param in_height Vertical pixel length of source frame.
     * @param in_width Horizontal pixel length of source frame.
     * @param kernel_size Kernel dimension constraint (assumed square, e.g., 3 for a 3x3 filter).
     * @param stride Stepping factor matching layer translation boundaries.
     * @param padding Dead margin pixel spacing boundaries expanded out around input grids.
     */
    static EngineStatus conv2d_forward(
        const float* __restrict input,
        const float* __restrict kernel,
        float* __restrict output,
        size_t in_channels,
        size_t out_channels,
        size_t in_height,
        size_t in_width,
        size_t kernel_size,
        size_t stride,
        size_t padding
    ) noexcept;
};